// Command gen-docs renders Markdown and a static GitHub Pages documentation site.
package main

import (
	"bytes"
	"fmt"
	"html"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/angelmsger/wecom-channel-cli/internal/app"
	"github.com/spf13/cobra"
	"github.com/yuin/goldmark"
	"github.com/yuin/goldmark/extension"
	"github.com/yuin/goldmark/parser"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func run() error {
	check := len(os.Args) > 1 && os.Args[1] == "--check"
	write := func(path string, data []byte) error {
		data = append(bytes.TrimSpace(data), '\n')
		if check {
			old, err := os.ReadFile(path)
			if err != nil || !bytes.Equal(old, data) {
				return fmt.Errorf("%s is stale; run make docs", path)
			}
			return nil
		}
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			return err
		}
		return os.WriteFile(path, data, 0644)
	}
	var md, body bytes.Buffer
	md.WriteString("# CLI reference\n\nGenerated by `make docs`; edit the command tree, not this file.\n\n")
	body.WriteString(`<h1>Command reference</h1><p>Generated from the actual command tree. Every flag, one searchable surface.</p><label for="command-search">Find a command or flag</label><input id="command-search" class="command-search" type="search" placeholder="Try: context, approval, --dry-run"><p id="search-summary" class="search-summary" aria-live="polite"></p>`)
	var walk func(*cobra.Command)
	walk = func(c *cobra.Command) {
		usage := strings.TrimSpace(c.UsageString())
		fmt.Fprintf(&md, "## %s\n\n%s\n\n```text\n%s\n```\n\n", c.CommandPath(), c.Short, usage)
		fmt.Fprintf(&body, `<section class="command-section" id="%s"><h2>%s</h2><p>%s</p><pre><code>%s</code></pre></section>`, strings.ReplaceAll(c.CommandPath(), " ", "-"), html.EscapeString(c.CommandPath()), html.EscapeString(c.Short), html.EscapeString(usage))
		for _, child := range c.Commands() {
			walk(child)
		}
	}
	walk(app.NewRootCmd())
	if err := write("docs/cli/README.md", md.Bytes()); err != nil {
		return err
	}
	if err := write("docs/cli/index.html", shell("Command reference", "../", "cli/index.html", body.String())); err != nil {
		return err
	}
	pages := []struct{ source, target, title string }{
		{"README.md", "guide.html", "Operator guide"}, {"docs/contexts.md", "contexts.html", "Channel contexts"},
		{"docs/security.md", "security.html", "Security model"}, {"docs/technical-design.md", "technical-design.html", "Technical design"},
		{"docs/watching.md", "watching.html", "Watching channels"},
		{"docs/research.md", "research.html", "API research"}, {"docs/releasing.md", "releasing.html", "Release guide"},
	}
	renderer := goldmark.New(goldmark.WithExtensions(extension.GFM), goldmark.WithParserOptions(parser.WithAutoHeadingID()))
	links := map[string]string{"README.md": "guide.html", "CONTRIBUTING.md": "https://github.com/AngelMsger/wecom-channel-cli/blob/main/CONTRIBUTING.md", "docs/cli/README.md": "cli/index.html"}
	for _, p := range pages {
		links[p.source] = p.target
	}
	re := regexp.MustCompile(`(href|src)="([^"#]+)(#[^"]*)?"`)
	for _, p := range pages {
		src, err := os.ReadFile(p.source)
		if err != nil {
			return err
		}
		var rendered bytes.Buffer
		if err = renderer.Convert(src, &rendered); err != nil {
			return err
		}
		content := re.ReplaceAllStringFunc(rendered.String(), func(s string) string {
			m := re.FindStringSubmatch(s)
			if strings.Contains(m[2], ":") || strings.HasPrefix(m[2], "/") {
				return s
			}
			resolved := filepath.ToSlash(filepath.Clean(filepath.Join(filepath.Dir(p.source), m[2])))
			dest, ok := links[resolved]
			if !ok {
				if strings.HasPrefix(resolved, "docs/") {
					dest = strings.TrimPrefix(resolved, "docs/")
				} else {
					dest = "https://github.com/AngelMsger/wecom-channel-cli/blob/main/" + resolved
				}
			}
			return m[1] + `="` + html.EscapeString(dest) + m[3] + `"`
		})
		if err = write("docs/"+p.target, shell(p.title, "", p.target, content)); err != nil {
			return err
		}
	}
	return nil
}
func shell(title, base, current, body string) []byte {
	var nav strings.Builder
	for _, p := range [][2]string{{"guide.html", "Operator guide"}, {"contexts.html", "Channel contexts"}, {"watching.html", "Watching channels"}, {"cli/index.html", "Command reference"}, {"security.html", "Security model"}, {"technical-design.html", "Technical design"}, {"research.html", "API research"}, {"releasing.html", "Release guide"}} {
		selected := ""
		if current == p[0] {
			selected = ` aria-current="page"`
		}
		fmt.Fprintf(&nav, `<a href="%s%s"%s>%s</a>`, base, p[0], selected, p[1])
	}
	return []byte(fmt.Sprintf(`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#f6f9ff"><title>%s — WeCom Channel CLI</title><link rel="icon" href="%sassets/mark.svg"><link rel="stylesheet" href="%sassets/site.css"><script src="%sassets/site.js" defer></script></head><body class="docs-page"><a class="skip" href="#main">Skip to content</a><header class="nav wrap"><a class="brand" href="%sindex.html" aria-label="WeCom Channel CLI home"><span class="brand-mark" aria-hidden="true"></span><span class="brand-name">WeCom Channel CLI</span></a><nav class="nav-links" aria-label="Main navigation"><a href="%scontexts.html">Contexts</a><a href="%sindex.html#playground">Explore the interface</a><a class="source-link" href="https://github.com/AngelMsger/wecom-channel-cli">GitHub ↗</a></nav></header><main id="main" class="wrap doc-layout"><aside class="doc-sidebar"><span class="eyebrow">DOCUMENTATION / 0.1.0</span>%s</aside><article class="doc-article">%s</article></main><footer class="wrap footer doc-footer"><span>wecom channel cli / MIT</span><p>An independent connector. Verify tenant access and worker isolation before deployment.</p><a href="%sindex.html">Back to home ↗</a></footer></body></html>`, html.EscapeString(title), base, base, base, base, base, base, nav.String(), body, base))
}
